def _email_ok(email: str) -> bool:
    """Syntax-only validation (no DNS lookup, so it works offline)."""
    if validate_email is None:
        return "@" in email and "." in email.split("@", 1)[1]
    try:
        validate_email(email, check_deliverability=False)
        return True
    except Exception:
        return False

