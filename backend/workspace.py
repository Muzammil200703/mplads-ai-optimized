@router.get("/me/saved-projects")
def list_saved_projects(
    current: models.User = Depends(auth.require_role("analyst")),
    db: Session = Depends(get_db),
):
    """Saved projects for the signed-in user, enriched with real risk data."""
    rows = (
        db.query(models.SavedProject, models.Project, models.RiskScore)
        .join(models.Project, models.Project.id == models.SavedProject.project_id)
        .outerjoin(models.RiskScore, models.RiskScore.project_id == models.SavedProject.project_id)
        .filter(models.SavedProject.user_id == current.id)
        .order_by(models.SavedProject.saved_at.desc())
        .all()
    )
    items = []
    for saved, project, risk in rows:
        items.append({
            "saved_at": saved.saved_at,
            "project_id": project.id,
            "project_name": project.project_name,
            "state": project.state,
            "constituency": project.constituency,
            "status": project.status,
            "sanctioned_amount": project.sanctioned_amount,
            "expenditure": project.expenditure,
            "risk_score": (risk.risk_score if risk else None),
            "risk_level": (risk.risk_level if risk else None),
            "ml_anomaly": (bool(risk.ml_anomaly) if risk else False),
        })
    return {"items": items, "total": len(items)}


@router.post("/me/saved-projects/{project_id}", status_code=201)
def save_project(
    project_id: int,
    current: models.User = Depends(auth.require_role("analyst")),
    db: Session = Depends(get_db),
):
    _project_or_404(db, project_id)
    existing = (
        db.query(models.SavedProject)
        .filter(models.SavedProject.user_id == current.id, models.SavedProject.project_id == project_id)
        .first()
    )
    if existing:
        return {"saved": True, "already_saved": True, "saved_at": existing.saved_at}
    row = models.SavedProject(user_id=current.id, project_id=project_id, saved_at=_now_iso())
    db.add(row)
    db.commit()
    return {"saved": True, "already_saved": False, "saved_at": row.saved_at}


