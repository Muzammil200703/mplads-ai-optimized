@router.post("/me/audit-cases/{project_id}", status_code=201)
def save_audit_case(
    project_id: int,
    current: models.User = Depends(auth.require_role("auditor")),
    db: Session = Depends(get_db),
):
    """Save the generated audit case for a project to the user's account.
    The case content is always regenerated from live data when opened, so
    nothing stored here can go stale or be fabricated."""
    project = _project_or_404(db, project_id)
    generated = audit_intel.build_audit_case(project, db)
    existing = (
        db.query(models.AuditCase)
        .filter(models.AuditCase.user_id == current.id, models.AuditCase.project_id == project_id)
        .first()
    )
    now = _now_iso()
    if existing:
        existing.case_id = generated["case_id"]
        existing.priority_tier = generated["priority"]["tier"]
        existing.priority_label = generated["priority"]["tier_label"]
        existing.risk_score = generated["risk"]["risk_score"]
        existing.risk_level = generated["risk"]["risk_level"]
        existing.created_at = now
        case_row = existing
    else:
        case_row = models.AuditCase(
            user_id=current.id,
            project_id=project.id,
            case_id=generated["case_id"],
            priority_tier=generated["priority"]["tier"],
            priority_label=generated["priority"]["tier_label"],
            risk_score=generated["risk"]["risk_score"],
            risk_level=generated["risk"]["risk_level"],
            status="Open",
            created_at=now,
        )
        db.add(case_row)
    db.commit()
    db.refresh(case_row)
    return {
        "case_row_id": case_row.id,
        "case_id": case_row.case_id,
        "project_id": project.id,
        "saved": True,
        "priority_tier": case_row.priority_tier,
        "priority_label": case_row.priority_label,
    }


@router.patch("/me/audit-cases/{project_id}")
def update_case_status(
    project_id: int,
    payload: CaseStatusUpdate,
    current: models.User = Depends(auth.require_role("auditor")),
    db: Session = Depends(get_db),
):
    if payload.status not in USER_STATUSES:
        raise HTTPException(status_code=400, detail=f"status must be one of {USER_STATUSES}")
    case = (
        db.query(models.AuditCase)
        .filter(models.AuditCase.user_id == current.id, models.AuditCase.project_id == project_id)
        .first()
    )
    if not case:
        raise HTTPException(status_code=404, detail="No saved case found for this project")
    case.status = payload.status
    # Keep the linked investigation status in step when present.
    inv = (
        db.query(models.UserInvestigation)
        .filter(models.UserInvestigation.user_id == current.id, models.UserInvestigation.project_id == project_id)
        .first()
    )
    if inv:
        inv.status = payload.status
        inv.updated_at = _now_iso()
    db.commit()
    return {"case_id": case.case_id, "case_status": case.status}


