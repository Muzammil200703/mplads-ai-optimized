# ═══════════════ Helpers ═══════════════

def _now_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S")


def _issue_token(user: models.User) -> str:
    return auth.create_access_token(user.id, user.role)


def _user_payload(user: models.User, token: str) -> dict:
    """Login/signup response. Includes effective capabilities so the UI can
    render role-aware navigation immediately without a follow-up /me call."""
    return {
        "user": UserOut.model_validate(user).model_dump()
        | {"capabilities": sorted(auth.user_capabilities(user))},
        "token": token,
        "token_type": "bearer",
    }


def _project_or_404(db: Session, project_id: int) -> models.Project:
    project = db.query(models.Project).filter(models.Project.id == project_id).first()
    if not project:
        raise HTTPException(status_code=404, detail=f"Project {project_id} not found")
    return project


def _owned_investigation(db: Session, user: models.User, project_id: int) -> models.UserInvestigation:
    inv = (
        db.query(models.UserInvestigation)
        .filter(models.UserInvestigation.user_id == user.id, models.UserInvestigation.project_id == project_id)
        .first()
    )
    if not inv:
        raise HTTPException(status_code=404, detail="No investigation found for this project")
    return inv


def _sync_user_investigation_record(db: Session, user: models.User, project: models.Project) -> models.UserInvestigation:
    """
    Create/update the per-user investigation record, deriving priority and
    recommendations from the real risk data via the existing audit_intel
    engine. Also ensures the shared evidence-checklist workspace exists so
    the drawer keeps working as before.
    """
    # Shared workspace (evidence checklist) — same behaviour as before.
    audit_intel.start_investigation(db, project)

    existing = (
        db.query(models.UserInvestigation)
        .filter(models.UserInvestigation.user_id == user.id, models.UserInvestigation.project_id == project.id)
        .first()
    )
    risk_row = db.query(models.RiskScore).filter(models.RiskScore.project_id == project.id).first()
    risk_score = risk_row.risk_score if risk_row else 0
    _rec_row = (
        db.query(models.ProjectRecInfo)
        .filter(models.ProjectRecInfo.project_id == project.id)
        .first()
    )
    _linked_exp = float(_rec_row.linked_expenditure or 0.0) if _rec_row is not None else 0.0
    tier = audit_intel.priority_breakdown(
        project, risk_score, risk_level=(risk_row.risk_level if risk_row else None),
        linked_expenditure=_linked_exp,
    )

    # Recommendations come straight from the recorded risk reasons.
    reasons = [r.strip() for r in (risk_row.reasons or "").split(",") if r.strip()] if risk_row else []

    now = _now_iso()
    if existing:
        existing.risk_score_at_start = risk_score
        existing.updated_at = now
        inv = existing
    else:
        inv = models.UserInvestigation(
            user_id=user.id,
            project_id=project.id,
            status="Open",
            priority_tier=tier["tier"],
            priority_label=tier["tier_label"],
            risk_score_at_start=risk_score,
            recommendations=None,
            created_at=now,
            updated_at=now,
        )
        db.add(inv)

    inv.priority_tier = tier["tier"]
    inv.priority_label = tier["tier_label"]
    inv.recommendations = json.dumps(reasons[:6]) if reasons else None
    db.commit()
    db.refresh(inv)
    return inv


