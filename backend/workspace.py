@router.post("/signup", status_code=201)
def signup(payload: SignupRequest, db: Session = Depends(get_db)):
    email = payload.email.lower().strip()
    if not _email_ok(email):
        raise HTTPException(status_code=400, detail="Invalid email address")
    if db.query(models.User).filter(models.User.email == email).first():
        raise HTTPException(status_code=409, detail="An account with this email already exists")

    user_count = db.query(models.User).count()
    # First registered account becomes admin (bootstrap).
    role = "admin" if user_count == 0 else payload.role

    user = models.User(
        name=payload.name.strip(),
        email=email,
        password_hash=auth.hash_password(payload.password),
        role=role,
        is_active=True,
        created_at=_now_iso(),
    )
    db.add(user)
    db.commit()
    db.refresh(user)
    return _user_payload(user, _issue_token(user))


@router.post("/login")
def login(payload: LoginRequest, db: Session = Depends(get_db)):
    email = payload.email.lower().strip()
    user = db.query(models.User).filter(models.User.email == email).first()
    # Uniform error: never reveal whether the email exists.
    if not user or not auth.verify_password(payload.password, user.password_hash):
        raise HTTPException(status_code=401, detail="Invalid email or password")
    if not user.is_active:
        raise HTTPException(status_code=403, detail="This account has been deactivated")
    return _user_payload(user, _issue_token(user))


@router.post("/forgot-password")
def forgot_password(payload: ForgotRequest, db: Session = Depends(get_db)):
    """
    Always returns 200 with the same message, whether or not the email exists
    (prevents account enumeration). Since there is no mail server in this
    deployment, the single-use token is returned for the requester to use —
    this is documented behaviour, not a fabricated email flow.
    """
    user = db.query(models.User).filter(models.User.email == payload.email.lower().strip()).first()
    message = "If an account exists for this email, a reset token has been generated."
    reset_token = None
    if user and user.is_active:
        token = auth.create_reset_token()
        expires = (datetime.now(timezone.utc) + timedelta(minutes=auth.RESET_TOKEN_EXPIRE_MINUTES)).strftime("%Y-%m-%dT%H:%M:%S")
        db.add(models.PasswordReset(
            user_id=user.id,
            token=token,
            expires_at=expires,
            used=False,
            created_at=_now_iso(),
        ))
        db.commit()
        reset_token = token
    return {"message": message, "reset_token": reset_token, "note": "Token is valid for 30 minutes and can be used once."}


@router.post("/reset-password")
def reset_password(payload: ResetRequest, db: Session = Depends(get_db)):
    row = (
        db.query(models.PasswordReset)
        .filter(models.PasswordReset.token == payload.token, models.PasswordReset.used.is_(False))
        .first()
    )
    if not row:
        raise HTTPException(status_code=400, detail="Invalid or already-used reset token")
    if row.expires_at < _now_iso():
        raise HTTPException(status_code=400, detail="Reset token has expired")
    user = db.query(models.User).filter(models.User.id == row.user_id).first()
    if not user:
        raise HTTPException(status_code=400, detail="Account no longer exists")
    user.password_hash = auth.hash_password(payload.new_password)
    row.used = True
    db.commit()
    return {"message": "Password updated. You can now sign in with the new password."}


